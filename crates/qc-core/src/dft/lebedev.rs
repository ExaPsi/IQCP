/// Get Lebedev grid data by number of angular points.
///
/// Returns a slice of \[x, y, z, w\] quadrature points on the unit sphere.
/// Supported sizes: 6, 38, 86, 194, 302, 590.
///
/// # Panics
///
/// Panics if `n_points` is not a supported grid size.
pub fn get_lebedev_grid(n_points: usize) -> &'static [[f64; 4]] {
    match n_points {
        6 => LEBEDEV_6,
        38 => LEBEDEV_38,
        86 => LEBEDEV_86,
        194 => LEBEDEV_194,
        302 => LEBEDEV_302,
        590 => LEBEDEV_590,
        _ => panic!(
            "Unsupported Lebedev grid size: {}. Supported: 6, 38, 86, 194, 302, 590",
            n_points
        ),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use approx::assert_abs_diff_eq;
    use std::f64::consts::PI;

    #[test]
    fn test_lebedev_weight_sums() {
        let four_pi = 4.0 * PI;
        for &n in &[6, 38, 86, 194, 302, 590] {
            let grid = get_lebedev_grid(n);
            let w_sum: f64 = grid.iter().map(|p| p[3]).sum();
            assert_abs_diff_eq!(w_sum, four_pi, epsilon = 1e-12);
        }
    }

    #[test]
    fn test_lebedev_unit_sphere() {
        for &n in &[6, 38, 86, 194, 302, 590] {
            let grid = get_lebedev_grid(n);
            for p in grid.iter() {
                let r2 = p[0] * p[0] + p[1] * p[1] + p[2] * p[2];
                assert_abs_diff_eq!(r2, 1.0, epsilon = 1e-14);
            }
        }
    }

    #[test]
    fn test_lebedev_integrates_y00_squared() {
        // Y_00 = 1 / sqrt(4*pi)
        // integral |Y_00|^2 d_omega = 1
        // sum(w * Y_00^2) = sum(w) / (4*pi) = 4*pi / (4*pi) = 1
        let grid = get_lebedev_grid(302);
        let y00_sq = 1.0 / (4.0 * PI);
        let integral: f64 = grid.iter().map(|p| p[3] * y00_sq).sum();
        assert_abs_diff_eq!(integral, 1.0, epsilon = 1e-12);
    }

    #[test]
    fn test_lebedev_integrates_y10() {
        // Y_10 = sqrt(3/(4*pi)) * z
        // integral Y_10 d_omega = 0 (by symmetry)
        let grid = get_lebedev_grid(302);
        let prefactor = (3.0 / (4.0 * PI)).sqrt();
        let integral: f64 = grid.iter().map(|p| p[3] * prefactor * p[2]).sum();
        assert!(integral.abs() < 1e-14, "integral Y_10 = {}", integral);
    }

    #[test]
    fn test_lebedev_integrates_y20_squared() {
        // Y_20 = sqrt(5/(16*pi)) * (3*z^2 - 1)
        // integral |Y_20|^2 d_omega = 1
        let grid = get_lebedev_grid(302);
        let prefactor = (5.0 / (16.0 * PI)).sqrt();
        let integral: f64 = grid
            .iter()
            .map(|p| {
                let y20 = prefactor * (3.0 * p[2] * p[2] - 1.0);
                p[3] * y20 * y20
            })
            .sum();
        assert_abs_diff_eq!(integral, 1.0, epsilon = 1e-10);
    }

    #[test]
    fn test_get_lebedev_grid_sizes() {
        assert_eq!(get_lebedev_grid(6).len(), 6);
        assert_eq!(get_lebedev_grid(38).len(), 38);
        assert_eq!(get_lebedev_grid(86).len(), 86);
        assert_eq!(get_lebedev_grid(194).len(), 194);
        assert_eq!(get_lebedev_grid(302).len(), 302);
        assert_eq!(get_lebedev_grid(590).len(), 590);
    }

    #[test]
    #[should_panic(expected = "Unsupported Lebedev grid size")]
    fn test_get_lebedev_grid_unsupported() {
        get_lebedev_grid(100);
    }
}
